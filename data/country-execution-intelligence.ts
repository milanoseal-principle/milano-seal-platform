export function getCountryExecutionIntelligence(
  slug: string,
  fallbackName = "Selected destination",
): CountryExecutionIntelligence {
  const intelligence = COUNTRY_EXECUTION_INTELLIGENCE[slug];

  if (intelligence) return intelligence;

  if (process.env.NODE_ENV !== "production") {
    console.warn(`[Milano Seal] Missing country execution intelligence for slug: ${slug}`);
  }

  return {
    slug,
    displayName: fallbackName,
    routeType: "authority_review",
    statusPill: "AUTHORITY CHECK",
    eyebrow: "EXECUTION INTELLIGENCE",
    routeLabel: "RECEIVING-AUTHORITY REVIEW ROUTE",
    authoritySummary: `Documents intended for ${fallbackName} are screened for notarial readiness, destination-use requirements, apostille/authentication routing, and controlled release coordination.`,
    executionFlags: ["Notarial Readiness", "Authority Review", "Route Control", "Release Packet"],
    executionPath: STANDARD_EXECUTION_PATH,
    trustLine: "Milano Seal routing snapshot — subject to receiving-authority review.",
    primaryCtaLabel: "Start Controlled Intake",
    secondaryCtaLabel: "Open Global Atlas",
  };
}
