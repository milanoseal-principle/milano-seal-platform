// Task 4 — Founder Operating System
// Typed domain model for the founder command center. INTERNAL operator data
// only. Money fields are nullable and every record carries a `dataKind`
// discriminator so nothing illustrative is ever shown as an actual figure.
// No fabricated revenue, leads, or projections presented as facts.

// Distinguishes confirmed operational facts from illustrative sample data and
// forward-looking projections. Anything not "actual" MUST be labeled in the UI.
export type DataKind = "actual" | "sample" | "projection";

export type FounderChannel =
  | "attorney"
  | "partner"
  | "government"
  | "international"
  | "direct";

export type PipelineChannel = "attorney" | "partner" | "government" | "international";

export type FollowUpStatus = "upcoming" | "due" | "overdue";

export type PipelineStage =
  | "identified"
  | "contacted"
  | "qualified"
  | "proposal"
  | "negotiation"
  | "won"
  | "lost";

// ---------------------------------------------------------------------------
// Daily command
// ---------------------------------------------------------------------------

export interface DailyCommandSummary {
  date: string; // ISO date (YYYY-MM-DD)
  dataKind: DataKind;
  // Confirmed revenue booked today. Null = not yet reported / unknown.
  revenueToday: number | null;
  // Quotes issued and still awaiting a decision.
  openQuotes: number;
  openQuotesValue: number | null;
  // Follow-ups requiring action today (due + overdue).
  followUpsDue: number;
  followUpsOverdue: number;
  // High-value matters flagged for founder attention.
  highValueMatters: number;
  // Content / marketing items scheduled or overdue.
  contentDue: number;
  // Short, honest headline generated by the assembler.
  headline: string;
}

// ---------------------------------------------------------------------------
// Follow-ups
// ---------------------------------------------------------------------------

export interface FollowUpItem {
  id: string;
  label: string;
  channel: FounderChannel;
  // ISO date of the last contact. Null = never contacted.
  lastContact: string | null;
  // Cadence in days after which a follow-up becomes due.
  cadenceDays: number;
  dataKind: DataKind;
  // Optional expected value of the relationship / matter.
  value: number | null;
  note?: string;
}

export interface DerivedFollowUp extends FollowUpItem {
  status: FollowUpStatus;
  // Days until due (negative = overdue). Null = never contacted (treated overdue).
  daysUntilDue: number | null;
  dueDate: string | null;
}

// ---------------------------------------------------------------------------
// Revenue review
// ---------------------------------------------------------------------------

export interface RevenueRecord {
  id: string;
  date: string; // ISO date
  amount: number | null;
  channel: FounderChannel;
  dataKind: DataKind;
  label?: string;
}

export interface RevenueReviewPeriod {
  periodKey: string; // e.g. "2026-W28" or "2026-07"
  granularity: "weekly" | "monthly";
  dataKind: DataKind;
  total: number;
  count: number;
  average: number; // guarded against divide-by-zero (0 when no records)
  byChannel: Record<FounderChannel, number>;
  // True when every underlying record was actual; false if any sample/projection.
  actualOnly: boolean;
}

// ---------------------------------------------------------------------------
// Content / marketing
// ---------------------------------------------------------------------------

export type ContentStatus = "idea" | "drafting" | "scheduled" | "published";

export type ContentFormat =
  | "article"
  | "email"
  | "social"
  | "video"
  | "case_study"
  | "newsletter";

export interface ContentQueueItem {
  id: string;
  title: string;
  format: ContentFormat;
  status: ContentStatus;
  // ISO date the item is scheduled to publish. Null = unscheduled.
  scheduledFor: string | null;
  channel: FounderChannel;
  dataKind: DataKind;
  note?: string;
}

export interface MarketingTask {
  id: string;
  label: string;
  dueDate: string | null; // ISO date, null = no deadline
  done: boolean;
  channel: FounderChannel;
  dataKind: DataKind;
}

// ---------------------------------------------------------------------------
// Pipeline (attorney / partner / government / international)
// ---------------------------------------------------------------------------

export interface PipelineItem {
  id: string;
  name: string;
  channel: PipelineChannel;
  stage: PipelineStage;
  value: number | null;
  lastContact: string | null;
  dataKind: DataKind;
  note?: string;
}

// ---------------------------------------------------------------------------
// KPIs
// ---------------------------------------------------------------------------

export interface KpiSnapshot {
  label: string;
  // Confirmed / observed value. Null = not yet measured.
  actual: number | null;
  // Optional target — always labeled as a projection, never as an actual.
  target: number | null;
  unit: "usd" | "count" | "percent";
  dataKind: DataKind;
}
