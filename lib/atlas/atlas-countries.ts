// Index for O(1) lookup
const _bySlug = new Map<string, AtlasCountry>(
  ATLAS_COUNTRIES.map((c) => [c.slug, c])
);

export function getAtlasCountry(slug: string): AtlasCountry | undefined {
  return _bySlug.get(slug.toLowerCase().trim());
}

export function getAtlasCountries(): AtlasCountry[] {
  return ATLAS_COUNTRIES;
}

export function getPrimaryAtlasCountries(): AtlasCountry[] {
  return ATLAS_COUNTRIES.filter((c) => c.priority === "primary" && c.slug !== "florida");
}
