create table if not exists public.seo_search_console_observations (
  id bigint generated by default as identity primary key,
  observed_date date not null,
  query text not null,
  page text not null,
  country_code text null,
  clicks numeric not null default 0,
  impressions numeric not null default 0,
  ctr numeric not null default 0,
  position numeric not null default 0,
  source text not null default 'google_search_console' check (source = 'google_search_console'),
  synced_at timestamptz not null default now(),
  unique (observed_date, query, page, country_code)
);

create index if not exists seo_gsc_page_date_idx on public.seo_search_console_observations(page, observed_date desc);
create index if not exists seo_gsc_query_date_idx on public.seo_search_console_observations(query, observed_date desc);
alter table public.seo_search_console_observations enable row level security;
revoke all on public.seo_search_console_observations from anon, authenticated;
grant select, insert, update, delete on public.seo_search_console_observations to service_role;

comment on table public.seo_search_console_observations is 'Verified Google Search Console observations. No ranking, traffic, Matter, or revenue values may be fabricated.';
